INSERT INTO fortunes (category_id, title, content, title_en, content_en, status)
SELECT c.id, h.title_fa, h.content_fa, h.title_en, h.content_en, 'ACTIVE'
FROM fortune_categories c
CROSS JOIN hafez_fortunes h
WHERE c.slug = 'hafez'
  AND NOT EXISTS (
    SELECT 1 FROM fortunes f
    WHERE f.category_id = c.id AND f.content = h.content_fa
  );
